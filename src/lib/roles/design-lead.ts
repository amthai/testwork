export function planTaskInstructions(opening: boolean) {
  return opening
    ? "Определи, остался ли после презентации существенный открытый вопрос с опорой в материалах. Если да, выбери next_topic и автора. Если подходящего вопроса нет, выбери wrap_up. По просьбе вернуться к показу выбери resume_presentation."
    : "Составь план одного следующего хода. Оцени предыдущий ответ по доступным основаниям."
}

